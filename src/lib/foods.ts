export function normalizeQuery(value: string): string {
  return value.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

export function searchFoods(query: string, custom: FoodItem[], limit = 30): FoodItem[] {
  const q = normalizeQuery(query);
  const names = new Set(custom.map((item) => normalizeQuery(item.name)));
  const codes = new Set(custom.map((item) => item.barcode).filter(Boolean));
  const all = [...custom, ...BASE_FOODS.filter((item) => !names.has(normalizeQuery(item.name)) && !(item.barcode && codes.has(item.barcode)))];
  if (!q) return all.slice(0, limit);
  const digits = q.replace(/\s/g, "");
  if (/^\d{8,14}$/.test(digits)) {
    const hit = all.filter((item) => item.barcode === digits);
    if (hit.length) return hit;
  }
  return all
    .filter((item) => normalizeQuery(item.name).includes(q))
    .slice(0, limit);
}

export function findByBarcode(code: string, custom: FoodItem[]): FoodItem | undefined {
  const digits = code.replace(/\s/g, "");
  return [...custom, ...BASE_FOODS].find((item) => item.barcode === digits);
}
