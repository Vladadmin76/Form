function toNutrients(row: Row): Nutrients {
  return roundNutrients({
    ...ZERO,
    kcal: row[1],
    protein: row[2],
    fat: row[3],
    carbs: row[4],
    fiber: row[5],
    iron: row[6],
    vitD: row[7],
    b12: row[8],
    omega3: row[9],
    calcium: row[10],
    magnesium: row[11],
    potassium: row[12],
    vitC: row[13],
    zinc: row[14],
    folate: row[15],
    sodium: row[16],
  });
}

