export function fallbackPhrase(tone: Tone, seed: string): string {
  const list = PHRASES[tone];
  let hash = 0;
  for (const char of seed) hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
  return list[hash % list.length] ?? list[0];
}
